import assert from 'node:assert/strict';
import {makeState} from '../dist/engine.mjs';
import {chordIdentity} from '../dist/chord-identity-v2.mjs';
import {chordCandidates} from '../dist/chord-discovery-v2.mjs';
import {projectChord} from '../dist/chord-projection-v2.mjs';
import {createLiveChordRecognizer,normalizeLiveChordShape} from '../dist/live-chord-recognition.mjs';

const state=makeState('meantone'),settings={limit:15,primeLimit:null,tol:10};
const shapeFor=ratio=>projectChord(state,chordIdentity(ratio),{tolerance:settings.tol}).notes.map(note=>note.coordinate);
const recognizer=createLiveChordRecognizer(),index=recognizer.prepare(state,settings);
assert.strictEqual(recognizer.prepare(state,settings),index,'unchanged contexts reuse the projected candidate index');
const harmonicCoords=shapeFor('4:5:6'),octaveStackCoords=shapeFor('2:5:6'),octaveCoords=shapeFor('1:2');
assert.deepEqual(normalizeLiveChordShape(harmonicCoords,state),[[0,0],[-2,4],[0,1]],'4:5:6 keeps its full period/generator coordinate shape');
assert.deepEqual(normalizeLiveChordShape(octaveStackCoords,state),[[0,0],[-1,4],[1,1]],'2:5:6 retains the octave displacement of its lower member');
assert.notDeepEqual(normalizeLiveChordShape(harmonicCoords,state),normalizeLiveChordShape(octaveStackCoords,state),'4:5:6 and 2:5:6 are distinct voicings');
assert.deepEqual(normalizeLiveChordShape(harmonicCoords.map(([p,g])=>[p+7,g-3]),state),normalizeLiveChordShape(harmonicCoords,state),'transposing every note by the same lattice vector preserves the chord');
assert.notDeepEqual(normalizeLiveChordShape([[...harmonicCoords[0]],[harmonicCoords[1][0]+1,harmonicCoords[1][1]],...harmonicCoords.slice(2)],state),normalizeLiveChordShape(harmonicCoords,state),'moving only one note by an octave changes the voicing');
assert.equal(normalizeLiveChordShape([[0,0],[0,0],[1,0]],state).length,2,'duplicate coordinates sound as one chord member');
assert.deepEqual(normalizeLiveChordShape(octaveCoords,state),[[0,0],[1,0]],'the octave interval remains a two-note 1:2 shape');
assert.throws(()=>normalizeLiveChordShape([[0,0.5]],state));

const recognized=text=>recognizer.recognize(state,shapeFor(text).map((coordinate,i)=>({coordinate,cents:i*100})),settings);
const harmonic=recognized('4:5:6');
assert.equal(harmonic.status,'match');
assert.ok(harmonic.matches.some(match=>match.label==='4:5:6'),'the familiar harmonic label is retained');
assert.deepEqual(recognized('4:5:6').matches.map(match=>match.id),harmonic.matches.map(match=>match.id),'ambiguous matches use a stable ranking');
const registerChord=recognized('2:5:6');
assert.ok(registerChord.matches.some(match=>match.label==='2:5:6'),'the octave-displaced chord has its own ratio label');
assert.notDeepEqual(harmonic.matches[0].shape,registerChord.matches[0].shape);
const raisedBassCoords=harmonicCoords.map(([p,g],i)=>i===0?[p+1,g]:[p,g]);
const raisedBass=recognizer.recognize(state,raisedBassCoords.map((coordinate,i)=>({coordinate,cents:i*100})),settings);
assert.equal(raisedBass.status,'match','raising the lowest member by one octave keeps the full played voicing recognizable');
assert.ok(raisedBass.matches.some(match=>match.label==='5:6:8'),'raising 4 in 4:5:6 produces the 5:6:8 identity');
const octave=recognizer.recognize(state,octaveCoords.map((coordinate,i)=>({coordinate,cents:i*1200})),settings);
assert.ok(octave.matches.some(match=>match.label==='1:2'),'octave-spaced notes are recognized as 1:2');
const reciprocal=recognized('1/6:5:4');
assert.equal(reciprocal.status,'match');
assert.ok(reciprocal.matches.some(match=>match.label==='1/6:5:4'),'the reciprocal uses its canonical compact spelling');
assert.equal(recognizer.recognize(state,[],settings).status,'empty');
assert.equal(recognizer.recognize(state,[{coordinate:[0,0],cents:0}],settings).status,'single-note');
assert.equal(recognizer.recognize(state,[[[0,0]],[[0,1]]],settings).status,'unavailable');
assert.equal(recognizer.recognize(state,Array.from({length:9},(_,i)=>({coordinate:[0,i],cents:i})),settings).reason,'too-many-notes');
const extraTone=[...harmonicCoords,[40,37]].map((coordinate,i)=>({coordinate,cents:i*100}));
assert.equal(recognizer.recognize(state,extraTone,settings).status,'no-match','extra distinct notes do not receive a partial chord label');
const stricter=recognizer.prepare(state,{...settings,tol:0});
assert.notStrictEqual(stricter,index,'tolerance changes rebuild eligibility');
const limited=recognizer.prepare(state,{...settings,limit:3});
assert.notStrictEqual(limited,stricter,'odd-limit changes rebuild eligibility');
for(const label of ['1:2','2:5:6','5:6:8'])assert.ok(chordCandidates().some(candidate=>candidate.label===label),`${label} belongs to the bounded chord catalogue`);
console.log('Register-sensitive chord matching, octave labels, complete sets and context caching passed.');
